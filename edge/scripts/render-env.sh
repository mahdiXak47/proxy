#!/usr/bin/env bash
# Render edge/.env from shared/endpoints.yml + shared/vault.yml.
# Run this on your WORKSTATION: the vault password never needs to touch the edge host.
# Then `make edge-sync` pushes edge/ (including .env) to the edge host.
set -euo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")/../.."

VAULT_PASS="${VAULT_PASS_FILE:-$HOME/.ansible/vault-pass-proxy}"
EP=shared/endpoints.yml
VAULT=shared/vault.yml

command -v ansible-vault >/dev/null || { echo "ERROR: ansible-vault not found" >&2; exit 1; }
[[ -f "$VAULT_PASS" ]] || { echo "ERROR: vault password file missing: $VAULT_PASS" >&2; exit 1; }
[[ -f "$VAULT" ]]      || { echo "ERROR: $VAULT missing - run 'make secrets-init'" >&2; exit 1; }

# Decrypt once into a variable; parse both sources with python3 (no yq dependency).
VAULT_PLAIN="$(ansible-vault view "$VAULT" --vault-password-file "$VAULT_PASS")"

umask 077
TMP="$(mktemp)"; trap 'rm -f "$TMP"' EXIT

EP_FILE="$EP" VAULT_PLAIN="$VAULT_PLAIN" python3 - > "$TMP" <<'PY'
import os, sys, re

# Minimal flat YAML reader: scalars and simple '- item' lists. Avoids a yq dependency.
def load(text):
    data, key = {}, None
    for raw in text.splitlines():
        line = '' if raw.strip().startswith('#') else raw.split('#', 1)[0].rstrip()
        if not line.strip() or line.strip() == '---':
            continue
        m = re.match(r'^(\S[^:]*):\s*(.*)$', line)
        if m:
            key, val = m.group(1).strip(), m.group(2).strip()
            data[key] = [] if val == '' else val.strip('"').strip("'")
        elif line.lstrip().startswith('- ') and key:
            item = line.lstrip()[2:].strip().strip('"').strip("'")
            if isinstance(data.get(key), list):
                data[key].append(item)
    return data

ep = load(open(os.environ['EP_FILE']).read())
vt = load(os.environ['VAULT_PLAIN'])
first = lambda v: v[0] if isinstance(v, list) else v

try:
    out = {
        'TZ': 'Asia/Tehran',
        'PANEL_DOMAIN': ep['panel_domain'],
        'TR_IP': ep['tr_ip'],
        'TR_PORT': ep['reality_port'],
        'REALITY_SNI': first(ep['reality_server_names']),
        'REALITY_SHORT_ID': first(ep['reality_short_ids']),
        'REALITY_FINGERPRINT': ep['reality_fingerprint'],
        'REALITY_PUBLIC_KEY': vt['vault_reality_public_key'],
        'TR_UUID': vt['vault_xray_client_uuid'],
        'EDGE_SOCKS_PORT': ep['edge_socks_port'],
        'EDGE_HTTP_PORT': ep['edge_http_port'],
    }
except KeyError as e:
    sys.exit(f"ERROR: missing key {e} in shared/endpoints.yml or shared/vault.yml")

bad = [k for k, v in out.items() if not str(v).strip() or 'REPLACE' in str(v)]
if bad:
    sys.exit("ERROR: unset/placeholder values: " + ", ".join(bad))

print("# GENERATED by edge/scripts/render-env.sh - do not edit, do not commit")
for k, v in out.items():
    print(f"{k}={v}")
PY

mv "$TMP" edge/.env
chmod 600 edge/.env
echo "wrote edge/.env ($(grep -c '=' edge/.env) values, mode $(stat -f %Lp edge/.env 2>/dev/null || stat -c %a edge/.env))"
