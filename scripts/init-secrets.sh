#!/usr/bin/env bash
# Generate the REALITY x25519 keypair + client UUID and write an encrypted shared/vault.yml.
# Idempotent guard: refuses to overwrite an existing vault (rotation is a deliberate act).
set -euo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")/.."

VAULT_PASS="${VAULT_PASS_FILE:-$HOME/.ansible/vault-pass-proxy}"
VAULT=shared/vault.yml

command -v ansible-vault >/dev/null || { echo "ERROR: ansible-vault not found" >&2; exit 1; }
command -v docker >/dev/null || { echo "ERROR: docker needed to run 'xray x25519'" >&2; exit 1; }

if [[ ! -f "$VAULT_PASS" ]]; then
  echo "ERROR: vault password file missing: $VAULT_PASS" >&2
  echo "  create it:  openssl rand -base64 32 > $VAULT_PASS && chmod 600 $VAULT_PASS" >&2
  exit 1
fi

if [[ -f "$VAULT" ]]; then
  echo "$VAULT already exists. To ROTATE keys deliberately:" >&2
  echo "  docker run --rm teddysun/xray xray x25519   # new keypair" >&2
  echo "  docker run --rm teddysun/xray xray uuid     # new uuid" >&2
  echo "  make secrets                                # paste them in" >&2
  echo "Then follow docs/runbook.md (exit first, then edge)." >&2
  exit 1
fi

echo "generating REALITY x25519 keypair..."
X25519="$(docker run --rm teddysun/xray xray x25519)"
# Output format varies by version: "Private key:"/"PrivateKey:" and "Public key:"/"Password:".
PRIV="$(echo "$X25519" | grep -iE 'private' | head -1 | sed 's/.*: *//' | tr -d '[:space:]')"
PUB="$(echo  "$X25519" | grep -iE 'public|password' | head -1 | sed 's/.*: *//' | tr -d '[:space:]')"
UUID="$(docker run --rm teddysun/xray xray uuid | tr -d '[:space:]')"

[[ -n "$PRIV" && -n "$PUB" && -n "$UUID" ]] || {
  echo "ERROR: could not parse generated material. Raw output was:" >&2
  echo "$X25519" >&2
  exit 1
}

umask 077
TMP="$(mktemp)"; trap 'rm -f "$TMP"' EXIT
cat > "$TMP" <<EOF
---
# Generated by scripts/init-secrets.sh. Edit with: make secrets
vault_reality_private_key: "$PRIV"
vault_reality_public_key: "$PUB"
vault_xray_client_uuid: "$UUID"
EOF

cp "$TMP" "$VAULT"
ansible-vault encrypt "$VAULT" --vault-password-file "$VAULT_PASS"
echo "wrote encrypted $VAULT"
echo
echo "Public key (needed by the edge, safe to show): $PUB"
echo "Client UUID (shared by both ends):             $UUID"
echo
echo "Next: fill shared/endpoints.yml (tr_ip, edge_ip, shortIds) and run 'make doctor'."
echo "Generate shortIds with: openssl rand -hex 4"
